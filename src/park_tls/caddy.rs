//! Generate Caddy file-TLS site blocks for park-plugin domains.

use super::store::{cert_paths, park_tls_root};
use std::collections::{HashMap, HashSet};
use std::io::Write;
use std::path::PathBuf;
use std::process::Command;

pub fn parked_caddyfile_path() -> PathBuf {
    park_tls_root().join("Caddyfile.parked")
}

/// Chat hub FQDN for remote `/chat` proxy (Linode publisher). Override with
/// `RELAY_CHAT_PRIMARY_FQDN` or `CHAT_PRIMARY_FQDN` (default `pub1.relaygateway.net`).
fn chat_primary_fqdn() -> String {
    std::env::var("RELAY_CHAT_PRIMARY_FQDN")
        .or_else(|_| std::env::var("CHAT_PRIMARY_FQDN"))
        .unwrap_or_else(|_| "pub1.relaygateway.net".into())
        .trim()
        .to_string()
}

fn is_chat_hub_node(node_fqdn: &str, hub: &str) -> bool {
    let node = node_fqdn.trim().to_ascii_lowercase();
    let hub = hub.trim().to_ascii_lowercase();
    if node.is_empty() || hub.is_empty() {
        return false;
    }
    if node == hub {
        return true;
    }
    // Short label match: pub1.relaygateway.net ↔ pub1.*
    let hub_short = hub.split('.').next().unwrap_or("");
    !hub_short.is_empty() && (node == hub_short || node.starts_with(&format!("{hub_short}.")))
}

/// Mesh live-chat sidecar handles (inserted before apex reverse_proxy).
/// Local chat-edge on :8098 when present; otherwise proxy API/WS to chat primary.
/// Never hairpin on the hub itself — that loops Caddy→public HTTPS→Caddy and
/// balloons memory / Recv-Q until the node looks down.
fn flashback_chat_sidecar_block() -> String {
    let local = std::net::TcpStream::connect_timeout(
        &"127.0.0.1:8098".parse().unwrap(),
        std::time::Duration::from_millis(200),
    )
    .is_ok();
    let node = std::env::var("RELAY_NODE_FQDN").unwrap_or_default();
    let hub = chat_primary_fqdn();
    let self_hub = is_chat_hub_node(&node, &hub);
    if local || self_hub {
        // Prefer loopback. On the hub, even if chat-edge is briefly down, do not
        // proxy to https://self — fail locally instead of a TLS hairpin storm.
        "\t# flashback-chat-sidecar\n\
\thandle /chat/api* {\n\
\t\treverse_proxy 127.0.0.1:8098\n\
\t}\n\
\thandle /chat/ws {\n\
\t\treverse_proxy 127.0.0.1:8098\n\
\t}\n"
            .to_string()
    } else {
        format!(
            "\t# flashback-chat-sidecar\n\
\thandle /chat/api* {{\n\
\t\treverse_proxy https://{hub} {{\n\
\t\t\theader_up Host flashbackrepository.org\n\
\t\t\ttransport http {{\n\
\t\t\t\ttls_server_name flashbackrepository.org\n\
\t\t\t}}\n\
\t\t}}\n\
\t}}\n\
\thandle /chat/ws {{\n\
\t\treverse_proxy https://{hub} {{\n\
\t\t\theader_up Host flashbackrepository.org\n\
\t\t\ttransport http {{\n\
\t\t\t\ttls_server_name flashbackrepository.org\n\
\t\t\t}}\n\
\t\t}}\n\
\t}}\n"
        )
    }
}

/// Write explicit host blocks with `tls <cert> <key>` for park domains.
///
/// Always unions `domains` with certificate directories on disk so a single-domain
/// cert fan-out cannot wipe other parked sites (historical bug).
/// Atomic: writes to `Caddyfile.parked.tmp` then renames.
/// Embeds Flashback `/chat/api*` + `/chat/ws` handles so park rewrites keep chat alive.
pub fn write_parked_caddyfile(domains: &HashMap<String, String>) -> std::io::Result<()> {
    let path = parked_caddyfile_path();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }

    let mut host_set: HashSet<String> = domains.keys().cloned().collect();
    let certs = park_tls_root().join("certs");
    if let Ok(rd) = std::fs::read_dir(&certs) {
        for e in rd.flatten() {
            if e.file_type().map(|t| t.is_dir()).unwrap_or(false) {
                if let Some(name) = e.file_name().to_str() {
                    host_set.insert(name.to_string());
                }
            }
        }
    }
    let mut hosts: Vec<String> = host_set.into_iter().collect();
    hosts.sort();

    let mut out = String::from("# Generated by relay-gateway park_tls plugin - do not edit\n");
    let upstream = std::env::var("RELAY_HTTP_PORT").unwrap_or_else(|_| "8080".into());
    let mut any = false;
    let chat_block = flashback_chat_sidecar_block();

    for host in &hosts {
        let (chain, key) = cert_paths(host);
        if !(chain.is_file() && key.is_file()) {
            continue;
        }
        any = true;
        if let Some(apex) = host.strip_prefix("www.") {
            if !apex.is_empty() {
                // Concatenate — do not put `{uri}` inside format! args that could confuse braces.
                out.push_str(host);
                out.push_str(" {\n\ttls ");
                out.push_str(&chain.display().to_string());
                out.push(' ');
                out.push_str(&key.display().to_string());
                out.push_str("\n\tredir https://");
                out.push_str(apex);
                out.push_str("{uri} permanent\n}\n\n");
                continue;
            }
        }
        out.push_str(host);
        out.push_str(" {\n\ttls ");
        out.push_str(&chain.display().to_string());
        out.push(' ');
        out.push_str(&key.display().to_string());
        out.push('\n');
        // Mesh chat sidecar on every parked apex (same Ergo; local or proxy to chat primary).
        out.push_str(&chat_block);
        out.push_str("\treverse_proxy 127.0.0.1:");
        out.push_str(&upstream);
        out.push_str(
            " {\n\t\ttransport http {\n\t\t\tdial_timeout 2s\n\t\t\tresponse_header_timeout 35s\n\t\t}\n\t}\n}\n\n",
        );
    }
    if !any {
        out.push_str("# (no park-tls certificates installed yet)\n");
    }

    let tmp = path.with_extension("parked.tmp");
    {
        let mut f = std::fs::File::create(&tmp)?;
        f.write_all(out.as_bytes())?;
        f.sync_all()?;
    }
    std::fs::rename(&tmp, &path)?;
    Ok(())
}

/// Best-effort `caddy reload` when the binary and Caddyfile are present.
pub fn reload_caddy() {
    let caddyfile = PathBuf::from("/etc/caddy/Caddyfile");
    if !caddyfile.is_file() {
        return;
    }
    match Command::new("caddy")
        .args(["reload", "--config", "/etc/caddy/Caddyfile"])
        .output()
    {
        Ok(o) if o.status.success() => tracing::info!("park_tls: caddy reloaded"),
        Ok(o) => tracing::warn!(
            status = %o.status,
            stderr = %String::from_utf8_lossy(&o.stderr),
            "park_tls: caddy reload failed"
        ),
        Err(e) => tracing::debug!(error = %e, "park_tls: caddy binary unavailable"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn flashback_chat_block_mentions_api_and_ws() {
        let b = flashback_chat_sidecar_block();
        assert!(b.contains("handle /chat/api*"), "{b}");
        assert!(b.contains("handle /chat/ws"), "{b}");
        assert!(b.contains("flashback-chat-sidecar"), "{b}");
    }

    #[test]
    fn chat_hub_detects_pub1_short_and_fqdn() {
        assert!(is_chat_hub_node(
            "pub1.relaygateway.net",
            "pub1.relaygateway.net"
        ));
        assert!(is_chat_hub_node("pub1", "pub1.relaygateway.net"));
        assert!(!is_chat_hub_node(
            "mesh1.relaygateway.net",
            "pub1.relaygateway.net"
        ));
    }

    #[test]
    fn remote_chat_block_uses_pub1_by_default() {
        // Ensure we are not on loopback :8098 in CI; unset hub self.
        std::env::remove_var("RELAY_NODE_FQDN");
        std::env::remove_var("RELAY_CHAT_PRIMARY_FQDN");
        std::env::remove_var("CHAT_PRIMARY_FQDN");
        // If something is listening on 8098 locally, skip remote assertion.
        let local = std::net::TcpStream::connect_timeout(
            &"127.0.0.1:8098".parse().unwrap(),
            std::time::Duration::from_millis(50),
        )
        .is_ok();
        if local {
            return;
        }
        let b = flashback_chat_sidecar_block();
        assert!(
            b.contains("https://pub1.relaygateway.net"),
            "expected pub1 hub proxy, got {b}"
        );
        assert!(!b.contains("iad1.relaygateway.net"), "{b}");
    }
}
